def save(con, data: dict):
    for k in REQUISITES:
        if k in data:
            comms.put(con, k, str(data[k] or "").strip())
    for slug in DOCS:
        key = f"text_{slug}"
        if key in data:
            v = (data[key] or "").strip()
            comms.put(con, f"legal_text_{slug}", "" if v == DOCS[slug][1].strip() else v)


