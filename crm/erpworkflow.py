def options(task) -> list[str]:
    # Не превращаем одноимённые личные/ручные задачи в системные цепочки ERP.
    student_id = task['student_id'] if 'student_id' in task.keys() else None
    source = task['source'] if 'source' in task.keys() else None
    if not student_id or source not in {'auto','life','erp','erp_rule'}:
        return []
    if task['kind'] in HOW_WAS:return HOW_WAS[task['kind']]
    return RULES.get((task['title'] or '').strip(),[])


def next_kind(title: str, current) -> str:
    if title=='Как прошло ПУ?':
        return 'erp_how_was_sms' if (current['title'] or '')=='Напоминание о ПУ (смс)' else 'erp_how_was_today'
    return KINDS.get(title,'manual')


def due_at(con, title: str, sid: int | None) -> datetime:
    now=datetime.now().replace(second=0,microsecond=0)
    if title=='Напоминание о ПУ (звонок)' and sid:
        row=con.execute('SELECT trial_at FROM students WHERE id=?',(sid,)).fetchone()
        if row and row['trial_at']:
            return datetime.fromisoformat(row['trial_at'][:16])-timedelta(hours=23,minutes=59)
    return now+DELAYS.get(title,timedelta(0))
