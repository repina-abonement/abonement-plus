SCHEMA = """
CREATE TABLE IF NOT EXISTS staff_acceptances (
    id INTEGER PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    doc TEXT NOT NULL,
    title TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    signed_name TEXT NOT NULL,
    accepted_at TEXT NOT NULL,
    ip TEXT NOT NULL DEFAULT '',
    user_agent TEXT NOT NULL DEFAULT '',
    text TEXT NOT NULL
);
"""


def init(con):
    con.executescript(SCHEMA)


def owner_id(con):
    r = con.execute("SELECT id FROM users WHERE role='admin' ORDER BY (login='admin') DESC, id LIMIT 1").fetchone()
    return r[0] if r else None


def _render(con, user: dict, t: str, base_url: str = "") -> str:
    from . import legal
    v = legal.requisites(con)
    for k, title in legal.REQUISITES.items():
        t = t.replace("{" + k + "}", v.get(k) or f"[{title}]")
    return t.replace("{name}", user.get("name", "")).replace("{site}", v.get("legal_site") or base_url)


def docs_for(con, user: dict, base_url: str = "") -> list[dict]:
    out = []
    for slug, title, t in DOCS:
        text = _render(con, user, t, base_url)
        # отпечаток считаем по тексту без адреса сайта из запроса: иначе проверка (без запроса) и подпись дают разное
        h = hashlib.sha256(_render(con, user, t, "").encode()).hexdigest()
        acc = con.execute("SELECT accepted_at FROM staff_acceptances WHERE user_id=? AND doc=? AND sha256=? ORDER BY id DESC LIMIT 1",
                          (user["id"], slug, h)).fetchone()
        out.append({"slug": slug, "title": title, "text": text, "sha256": h, "accepted_at": acc[0] if acc else None})
    return out


def pending(con, user: dict) -> int:
    if user["id"] == owner_id(con):
        return 0
    return sum(1 for d in docs_for(con, user) if not d["accepted_at"])


def accept(con, user: dict, slugs: list, signed_name: str, ip: str, ua: str, base_url: str = "") -> int:
    from .services import ApiError
    docs = {d["slug"]: d for d in docs_for(con, user, base_url)}
    need = [s for s, d in docs.items() if not d["accepted_at"]]
    if set(need) - set(slugs or []):
        raise ApiError("Отметьте все документы")
    nm = " ".join((signed_name or "").split())
    if len(nm) < 3 or not set(nm.lower().replace("ё", "е").split()) & set(user.get("name", "").lower().replace("ё", "е").split()):
        raise ApiError("Впишите свои фамилию и имя, как в CRM: " + user.get("name", ""))
    now = datetime.now().isoformat(timespec="seconds")
    for s in need:
        d = docs[s]
        con.execute("""INSERT INTO staff_acceptances(user_id, doc, title, sha256, signed_name, accepted_at, ip, user_agent, text)
                       VALUES (?,?,?,?,?,?,?,?,?)""", (user["id"], s, d["title"], d["sha256"], nm, now, ip[:60], (ua or "")[:300], d["text"]))
    return len(need)


def log(con, uid: int) -> list[dict]:
    return [dict(r) for r in con.execute(
        "SELECT id, doc, title, sha256, signed_name, accepted_at, ip, user_agent FROM staff_acceptances WHERE user_id=? ORDER BY id DESC", (uid,))]


def overview(con) -> list[dict]:
    out = []
    oid = owner_id(con)
    for u in con.execute("SELECT id, name, role FROM users WHERE active=1 ORDER BY role, name").fetchall():
        if u["id"] == oid:
            continue
        p = pending(con, dict(u))
        last = con.execute("SELECT MAX(accepted_at) FROM staff_acceptances WHERE user_id=?", (u["id"],)).fetchone()[0]
        from . import tour
        out.append({"id": u["id"], "name": u["name"], "pending": p, "last": last, "tour": tour.done_at(con, u["id"])})
    return out
