function tourFor(u) {
  if (u.role === "coach") {
    const prom = !!u.is_promoter;
    return { steps: TOUR_COACH.filter((s) => !s.promoter || prom), pool: prom ? [...QUIZ_COACH, ...QUIZ_PROMOTER] : QUIZ_COACH, must: prom ? QUIZ_PROMOTER[0] : null };
  }
  if (u.role === "lawyer") return { steps: TOUR_LAWYER, pool: QUIZ_LAWYER };
  if (u.role === "operator" && u.is_senior) return { steps: TOUR_SENIOR, pool: QUIZ_SENIOR };
  return { steps: TOUR_ADMIN, pool: QUIZ_ADMIN };
}
const shuffle = (arr) => { const a = [...arr]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const mixAnswers = (x) => { const order = shuffle(x.a.map((_, j) => j)); return { ...x, a: order.map((j) => x.a[j]), ok: order.indexOf(0) }; };

/* видимая кнопка раздела в меню (на компьютере сбоку, на телефоне снизу); папку в меню раскрываем */
function tourTarget(s) {
  if (s.el) { const e = document.querySelector(s.el); return e && e.offsetParent ? e : null; }
  if (!s.view) return null;
  const f = [...document.querySelectorAll(".nav-fold")].find((x) => x.querySelector(`[data-view="${s.view}"]`));
  if (f) f.classList.add("open");
  return [...document.querySelectorAll(`.nav [data-view="${s.view}"], .tabbar [data-view="${s.view}"]`)].find((e) => e.offsetParent) || null;
}

