function tourFor(u) {
  if (u.role === "coach") {
    const prom = !!u.is_promoter;
    const steps = TOUR_COACH.filter((s) => !s.promoter || prom);
    const quiz = prom ? [QUIZ_COACH[0], QUIZ_PROMOTER_2, QUIZ_COACH[2]] : QUIZ_COACH;
    return { steps, quiz };
  }
  if (u.role === "lawyer") return { steps: TOUR_LAWYER, quiz: QUIZ_LAWYER };
  if (u.role === "operator" && u.is_senior) return { steps: TOUR_SENIOR, quiz: QUIZ_SENIOR };
  return { steps: TOUR_ADMIN, quiz: QUIZ_ADMIN };
}

/* видимая кнопка раздела в меню (на компьютере сбоку, на телефоне снизу); папку в меню раскрываем */
function tourTarget(s) {
  if (s.el) { const e = document.querySelector(s.el); return e && e.offsetParent ? e : null; }
  if (!s.view) return null;
  const f = [...document.querySelectorAll(".nav-fold")].find((x) => x.querySelector(`[data-view="${s.view}"]`));
  if (f) f.classList.add("open");
  return [...document.querySelectorAll(`.nav [data-view="${s.view}"], .tabbar [data-view="${s.view}"]`)].find((e) => e.offsetParent) || null;
}

function startTour(again = false) {
  if (S.tourOn) return;
  S.tourOn = true;
  let { steps, quiz } = tourFor(S.user);
  const shown = (v) => visibleViews().some(([k]) => k === v);
  const list = steps.filter((s) => !s.view || shown(s.view));
  let i = 0;
  const wrap = document.createElement("div");
  wrap.className = "tour";
  wrap.innerHTML = `<div class="tour-block"></div><div class="tour-card" role="dialog" aria-modal="true"></div>`;
  document.body.appendChild(wrap);
  const card = wrap.querySelector(".tour-card");
  const clearHi = () => document.querySelectorAll(".tour-hi").forEach((e) => e.classList.remove("tour-hi"));
  const total = list.length + 1;

  const showStep = () => {
    clearHi();
    const s = list[i];
    if (s.view && S.view !== s.view) go(s.view);
    setTimeout(() => { const t = tourTarget(s); if (t) { t.classList.add("tour-hi"); t.scrollIntoView({ block: "nearest" }); } }, 60);
    card.innerHTML = `<div class="tour-step">Шаг ${i + 1} из ${total}</div>
      <div class="tour-bar"><i style="width:${Math.round(((i + 1) / total) * 100)}%"></i></div>
      <h3>${esc(s.title)}</h3><p>${esc(s.text)}</p>
      <div class="tour-btns">${i ? `<button class="btn" data-tb="back">← Назад</button>` : ""}<button class="btn primary" data-tb="next">${i === list.length - 1 ? "К вопросам →" : "Дальше →"}</button></div>`;
    card.querySelector('[data-tb="next"]').onclick = () => { if (i < list.length - 1) { i++; showStep(); } else showQuiz(); };
    const b = card.querySelector('[data-tb="back"]'); if (b) b.onclick = () => { i--; showStep(); };
  };

  const showQuiz = () => {
    clearHi();
    // варианты перемешиваем, чтобы верный не стоял всегда на одном месте
    quiz = quiz.map((x) => {
      const order = x.a.map((_, j) => j).sort(() => Math.random() - 0.5);
      return { ...x, a: order.map((j) => x.a[j]), ok: order.indexOf(0) };
    });
    const picked = quiz.map(() => null);
    const draw = () => {
      const allOk = quiz.every((x, k) => picked[k] === x.ok);
      card.innerHTML = `<div class="tour-step">Шаг ${total} из ${total}</div><div class="tour-bar"><i style="width:100%"></i></div>
        <h3>${S.user.role === "coach" ? "Финальный свисток: 3 вопроса" : "Проверим: 3 вопроса"}</h3>
        ${quiz.map((x, k) => `<div class="tour-q"><b>${k + 1}. ${esc(x.q)}</b>
          ${x.a.map((t, j) => {
            const st = picked[k] === j ? (j === x.ok ? "ok" : "bad") : "";
            return `<button class="tour-a ${st}" data-q="${k}" data-a="${j}">${st === "ok" ? "✅ " : st === "bad" ? "✖ " : ""}${esc(t)}</button>`;
          }).join("")}
          ${picked[k] !== null && picked[k] !== x.ok ? `<div class="tour-hint">Не совсем. ${esc(x.hint || "Попробуй ещё раз")}</div>` : ""}</div>`).join("")}
        <div class="tour-btns"><button class="btn" data-tb="back">← К разделам</button>
          <button class="btn primary" data-tb="done" ${allOk ? "" : "disabled"}>${allOk ? "Готово, поехали! 🚀" : "Ответь на все вопросы"}</button></div>`;
      card.querySelectorAll("[data-q]").forEach((b) => (b.onclick = () => { picked[+b.dataset.q] = +b.dataset.a; draw(); }));
      card.querySelector('[data-tb="back"]').onclick = () => { i = 0; showStep(); };
      card.querySelector('[data-tb="done"]').onclick = async () => {
        try { await api("POST", "/api/tour/done", {}); } catch (e) { return fail(e); }
        S.meta.tour_pending = false; S.tourOn = false; wrap.remove();
        toast(S.user.role === "coach" ? "Обучение пройдено! Выходи на поле ⚽" : "Обучение пройдено, хорошей работы!");
        go(visibleViews()[0][0]);
        if (!again) offerAlerts();
      };
      card.scrollTop = 0;
    };
    draw();
  };
  showStep();
}
